#!/usr/bin/env bash
# =============================================================================
# Build ocio binary directly calling CMake and copy to dist/cmake/
# Optionally runs CPack to package the application.
# =============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
source "${SCRIPT_DIR}/lib/pause.sh"
BUILD_DIR="${BUILD_DIR:-${ROOT_DIR}/build}"
DIST_DIR="${DIST_DIR:-${ROOT_DIR}/dist}"
CMAKE_DIST_DIR="${DIST_DIR}/cmake"

RUN_CPACK=false
CPACK_GENS=""
export PAUSE_MODE=false
DRY_RUN=false
CMAKE_ARGS=()

usage() {
    cat <<EOF
Usage: $(basename "$0") [OPTIONS] [-- CMAKE_OPTIONS]

Build the ocio application using CMake and place artifacts into dist/cmake/.

Options:
  --cpack [GENERATORS]   Run CPack after building. Optionally provide semicolon- or
                         comma-separated generators (e.g. "tgz;rpm", "DEB;RPM").
  -p, --pause            Pause and wait for [Enter] before executing each command.
  -d, --dry-run          Dry-run mode: only print commands without executing them.
  -h, --help             Show this help message.

Additional arguments (such as -DRAYLIB_MODE=LOCAL) are forwarded directly to cmake.
EOF
    exit 0
}

# Normalize generator names (e.g. tgz -> TGZ, rpm -> RPM, deb -> DEB)
normalize_cpack_generators() {
    local input="$1"
    local IFS=';,'
    read -ra raw_gens <<< "${input}"
    local normalized=()
    for gen in "${raw_gens[@]}"; do
        gen="$(echo "${gen}" | xargs)"
        [ -z "${gen}" ] && continue
        local upper="${gen^^}"
        case "${upper}" in
            TGZ|RPM|DEB|ZIP|TAR|TBZ2|TXZ|TZ|TZST|STGZ|7Z)
                normalized+=("${upper}")
                ;;
            APPIMAGE)
                normalized+=("AppImage")
                ;;
            NUGET)
                normalized+=("NuGet")
                ;;
            *)
                normalized+=("${gen}")
                ;;
        esac
    done
    local IFS=';'
    echo "${normalized[*]}"
}

while [ $# -gt 0 ]; do
    case "$1" in
        --cpack)
            RUN_CPACK=true
            if [ $# -gt 1 ] && [[ "$2" != -* ]]; then
                CPACK_GENS="$2"
                shift 2
            else
                shift
            fi
            ;;
        --cpack=*)
            RUN_CPACK=true
            CPACK_GENS="${1#--cpack=}"
            shift
            ;;
        -p|--pause)
            PAUSE_MODE=true
            shift
            ;;
        -d|--dry-run)
            DRY_RUN=true
            shift
            ;;
        -pd|-dp)
            PAUSE_MODE=true
            DRY_RUN=true
            shift
            ;;
        -h|--help)
            usage
            ;;
        --)
            shift
            CMAKE_ARGS+=("$@")
            break
            ;;
        *)
            CMAKE_ARGS+=("$1")
            shift
            ;;
    esac
done

say "CMake generates a Makefile (or Ninja file) from CMakeLists.txt. We configure, build, and copy the binary to dist/cmake/."

demo_cmd "mkdir -p \"${CMAKE_DIST_DIR}\"" "Ensuring the dist/cmake/ output directory exists."
demo_cmd "mkdir -p \"${BUILD_DIR}\"" "Ensuring the build directory exists."

echo "==> Configuring ocio with CMake..."
demo_cmd "cmake -S \"${ROOT_DIR}\" -B \"${BUILD_DIR}\" -DCMAKE_BUILD_TYPE=Release ${CMAKE_ARGS[*]:-}" \
    "Configuring the CMake build (Release) in ${BUILD_DIR}."

echo "==> Building ocio binary..."
demo_cmd "cmake --build \"${BUILD_DIR}\" --config Release --target ocio -j\"\$(nproc)\"" \
    "Building the ocio binary with all available cores."

BINARY_PATH=""
if [ "${DRY_RUN}" = true ]; then
    BINARY_PATH="${BUILD_DIR}/bin/ocio"
elif [ -f "${BUILD_DIR}/bin/ocio" ]; then
    BINARY_PATH="${BUILD_DIR}/bin/ocio"
elif [ -f "${BUILD_DIR}/ocio" ]; then
    BINARY_PATH="${BUILD_DIR}/ocio"
else
    echo "Error: ocio binary not found in ${BUILD_DIR}/bin or ${BUILD_DIR}" >&2
    exit 1
fi

echo "==> Copying binary to ${CMAKE_DIST_DIR}/ocio..."
demo_cmd "cp -f \"${BINARY_PATH}\" \"${CMAKE_DIST_DIR}/ocio\" && chmod +x \"${CMAKE_DIST_DIR}/ocio\"" \
    "Copying the compiled binary into dist/cmake/ and marking it executable."

if [ "${RUN_CPACK}" = true ]; then
    say "CPack reads CPackConfig.cmake (generated by CMake) and produces distributable archives. Each generator (TGZ, RPM, DEB, AppImage, ...) produces a different artifact."
    echo "==> Packaging with CPack..."
    CPACK_CMD=("cpack" "--config" "${BUILD_DIR}/CPackConfig.cmake" "-B" "${BUILD_DIR}")
    if [ -n "${CPACK_GENS}" ]; then
        NORMALIZED_GENS="$(normalize_cpack_generators "${CPACK_GENS}")"
        echo "==> CPack generator(s): ${NORMALIZED_GENS}"
        CPACK_CMD+=("-G" "${NORMALIZED_GENS}")
    fi
    demo_cmd "${CPACK_CMD[*]}" "Running CPack to generate the package artifact(s)."

    echo "==> Copying CPack output to ${CMAKE_DIST_DIR}..."
    demo_cmd "find \"${BUILD_DIR}\" -maxdepth 1 -type f \\( -name '*.rpm' -o -name '*.deb' -o -name '*.tar.gz' -o -name '*.tgz' -o -name '*.tar.xz' -o -name '*.zip' -o -name '*.7z' -o -name '*.sh' \\) -exec cp -f {} \"${CMAKE_DIST_DIR}/\" \\;" \
        "Copying the generated CPack artifacts into dist/cmake/."
fi

echo "==> Artifacts in ${CMAKE_DIST_DIR}:"
if [ "${DRY_RUN}" = true ]; then
    echo "  (dry-run: skipping listing of ${CMAKE_DIST_DIR})"
else
    ls -lh "${CMAKE_DIST_DIR}"
fi
